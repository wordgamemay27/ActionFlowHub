export function getCatalogLang(lang: SupportedLang): CatalogLang {
  if (SUPPORTED_LANGS.includes(lang)) {
    return lang;
  }
  return 'en';
}

interface LanguageContextValue {
  lang: SupportedLang;
  setLang: (lang: SupportedLang) => void;
  cycleLanguage: () => void;
  t: TranslationStrings;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'it',
  setLang: () => {},
  cycleLanguage: () => {},
  t: TRANSLATIONS.it,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<SupportedLang>(() => {
    try {
      const saved = localStorage.getItem('af_lang_v1') as SupportedLang | null;
      if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
    } catch {
      // ignore
    }
    return 'it';
  });

  const setLang = useCallback((next: SupportedLang) => {
    setLangState(next);
    try {
      localStorage.setItem('af_lang_v1', next);
    } catch {
      // ignore
    }
  }, []);

  const cycleLanguage = useCallback(() => {
    setLangState((prev) => {
      const idx = SUPPORTED_LANGS.indexOf(prev);
      const next = SUPPORTED_LANGS[(idx + 1) % SUPPORTED_LANGS.length];
      try {
        localStorage.setItem('af_lang_v1', next);
      } catch {
        // ignore
      }
      return next;
    });
  }, []);

  const t = TRANSLATIONS[lang] || TRANSLATIONS.it;

  return (
    <LanguageContext.Provider value={{ lang, setLang, cycleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export function useTranslation(): LanguageContextValue {
  return useContext(LanguageContext);
}
